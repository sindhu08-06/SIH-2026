export const SUPPORTED_LANGUAGES: { code: Language; name: string; nativeName: string }[] = [
  { code: 'en', name: 'English', nativeName: 'English' },
  { code: 'hi', name: 'Hindi', nativeName: 'हिन्दी' },
  { code: 'mr', name: 'Marathi', nativeName: 'मराठी' },
  { code: 'te', name: 'Telugu', nativeName: 'తెలుగు' },
];

export function cycleLanguage(current: Language): Language {
  const order: Language[] = ['en', 'hi', 'mr', 'te'];
  const idx = order.indexOf(current);
  return order[(idx + 1) % order.length];
}

export function getLanguageNativeName(lang: Language): string {
  const found = SUPPORTED_LANGUAGES.find((l) => l.code === lang);
  return found ? found.nativeName : 'English';
}

export function getCategoryLocalized(catId: string, lang: Language): string {
  const normalized = catId.toLowerCase();
  if (normalized === 'all') return getTranslation(lang, 'catAll');
  if (normalized.includes('elect') || normalized.includes('power')) return getTranslation(lang, 'catElectrical');
  if (normalized.includes('plumb') || normalized.includes('drain')) return getTranslation(lang, 'catPlumbing');
  if (normalized.includes('appliance') || normalized.includes('ac ') || normalized.includes('repair')) return getTranslation(lang, 'catAppliance');
  if (normalized.includes('carpent') || normalized.includes('wood') || normalized.includes('lock')) return getTranslation(lang, 'catCarpentry');
  if (normalized.includes('solar') || normalized.includes('inverter')) return getTranslation(lang, 'catSolar');
  if (normalized.includes('clean') || normalized.includes('sanitat')) return getTranslation(lang, 'catCleaning');
  if (normalized.includes('emerg') || normalized.includes('sos')) return getTranslation(lang, 'catEmergency');
  return catId;
}

export function getBookingStatusLabel(status: string, lang: Language): string {
  switch (status) {
    case 'open':
      return getTranslation(lang, 'customerOrderStatusOpen');
    case 'assigned':
      return getTranslation(lang, 'customerOrderStatusAssigned');
    case 'in_transit':
      return getTranslation(lang, 'customerOrderStatusInTransit');
    case 'in_progress':
      return getTranslation(lang, 'customerOrderStatusInProgress');
    case 'completed':
      return getTranslation(lang, 'customerOrderStatusCompleted');
    case 'cancelled':
      return getTranslation(lang, 'customerOrderStatusCancelled');
    default:
      return status;
  }
}

